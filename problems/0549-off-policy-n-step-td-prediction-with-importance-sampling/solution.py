import numpy as np

def off_policy_nstep_td(
    episodes: list,
    behavior_policy: list,
    target_policy: list,
    num_states: int,
    num_actions: int,
    n: int,
    alpha: float,
    gamma: float
) -> np.ndarray:
    """
    Off-policy n-step TD prediction for state values using importance sampling.
    """
    V = np.zeros(num_states, dtype=float)

    for episode in episodes:
        T = len(episode)

        for t in range(T):
            state, _, _ = episode[t]

            # Number of rewards included in this return
            end = min(t + n, T)

            # Compute n-step / truncated return
            G = 0.0
            for k in range(t, end):
                _, _, reward = episode[k]
                G += (gamma ** (k - t)) * reward

            # Bootstrap if the n-step lookahead does not reach terminal state
            if t + n < T:
                next_state = episode[t + n][0]
                G += (gamma ** n) * V[next_state]

            # Importance sampling ratio over the n-step window.
            # Actions t through end-1 contributed to G.
            rho = 1.0

            for k in range(t, end):
                s_k, a_k, _ = episode[k]

                b = behavior_policy[s_k][a_k]
                pi = target_policy[s_k][a_k]

                # If behavior probability is zero, this trajectory
                # could not have been generated by the behavior policy.
                if b == 0:
                    rho = 0.0
                    break

                rho *= pi / b

            # TD update
            V[state] += alpha * rho * (G - V[state])

    return V